-- Payments marketplace source schema (PLAN G1). Documented in docs/schema.md.
-- Ids: the generator supplies explicit ids (1, 2, ...) so its operation stream is deterministic.
-- Ad-hoc inserts (smoke test, G11 prober) use the identity default, which starts at 1e12.

CREATE TABLE customers (
    id             bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    full_name      text NOT NULL,          -- PII
    email          text NOT NULL,          -- PII
    phone          text NOT NULL,          -- PII
    address        text NOT NULL,          -- PII
    date_of_birth  date NOT NULL,          -- PII
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE merchants (
    id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    name        text NOT NULL,
    category    text NOT NULL,
    country     char(2) NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE accounts (
    id           bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    owner_type   text NOT NULL CHECK (owner_type IN ('customer', 'merchant')),
    customer_id  bigint REFERENCES customers (id),
    merchant_id  bigint REFERENCES merchants (id),
    currency     char(3) NOT NULL,
    balance      numeric(14, 2) NOT NULL,  -- maintained in the same transaction as each money movement
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CHECK ((owner_type = 'customer') = (customer_id IS NOT NULL AND merchant_id IS NULL)),
    CHECK ((owner_type = 'merchant') = (merchant_id IS NOT NULL AND customer_id IS NULL))
);

CREATE TABLE transactions (
    id                bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    txn_type          text NOT NULL CHECK (txn_type IN ('payment', 'topup')),
    customer_id       bigint NOT NULL REFERENCES customers (id),
    merchant_id       bigint REFERENCES merchants (id),
    payer_account_id  bigint REFERENCES accounts (id),   -- NULL for topup (external funding)
    payee_account_id  bigint NOT NULL REFERENCES accounts (id),
    amount            numeric(12, 2) NOT NULL CHECK (amount > 0),
    currency          char(3) NOT NULL,
    status            text NOT NULL,
    description       text NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK ((txn_type = 'payment') = (merchant_id IS NOT NULL AND payer_account_id IS NOT NULL))
);

CREATE TABLE refunds (
    id              bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    transaction_id  bigint NOT NULL UNIQUE REFERENCES transactions (id),
    amount          numeric(12, 2) NOT NULL CHECK (amount > 0),
    reason          text NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE support_tickets (
    id           bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    customer_id  bigint NOT NULL REFERENCES customers (id),
    subject      text NOT NULL,
    body         text NOT NULL,            -- free text; may contain PII (name, email)
    status       text NOT NULL CHECK (status IN ('open', 'pending', 'resolved', 'closed')),
    priority     text NOT NULL,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE help_articles (
    id          bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000000000000) PRIMARY KEY,
    title       text NOT NULL,
    body        text NOT NULL,             -- some ~10 KB, stored out of line (TOAST)
    category    text NOT NULL,
    view_count  integer NOT NULL DEFAULT 0,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX ON accounts (customer_id);
CREATE INDEX ON accounts (merchant_id);
CREATE INDEX ON transactions (customer_id);
CREATE INDEX ON support_tickets (customer_id);

-- Text/PII tables: full before-images and no TOAST placeholders (PLAN G2).
ALTER TABLE customers REPLICA IDENTITY FULL;
ALTER TABLE support_tickets REPLICA IDENTITY FULL;
ALTER TABLE help_articles REPLICA IDENTITY FULL;

-- Heartbeat target so the slot advances when tracked tables are idle (PLAN G2).
CREATE TABLE dbz_heartbeat (id int PRIMARY KEY, ts timestamptz NOT NULL);

-- Generator progress, written in the same transaction as each logical transaction, so the next
-- run resumes the deterministic sequence exactly. Outside schema public, so outside the publication.
CREATE SCHEMA gen;
CREATE TABLE gen.state (
    id          int PRIMARY KEY CHECK (id = 1),
    seed        bigint NOT NULL,
    next_txn    bigint NOT NULL,
    updated_at  timestamptz NOT NULL DEFAULT now()
);

